export type AvatarDecorationKind =
  | "sparkles"
  | "orbit"
  | "crown"
  | "wings"
  | "flame"
  | "flora"
  | "crystal"
  | "hearts"
  | "runes"
  | "halo";

export type ProfileDecorationKind =
  | "stars"
  | "aurora"
  | "grid"
  | "petals"
  | "embers"
  | "snow"
  | "ribbons"
  | "constellation";

export interface AvatarDecoration {
  id: string;
  label: string;
  description: string;
  kind: AvatarDecorationKind;
  colours: readonly [string, string];
  animated: boolean;
  variant: number;
}

export interface ProfileDecoration {
  id: string;
  label: string;
  description: string;
  kind: ProfileDecorationKind;
  colours: readonly [string, string];
  animated: boolean;
  variant: number;
}

