export interface CustomEmoji {
  id: string;
  name: string;
  url: string | null;
  animated: boolean;
  serverId: string;
  serverName?: string;
}

export const CUSTOM_EMOJI_PATTERN = /<:([a-zA-Z0-9_]{2,32}):([a-z0-9]+)>/g;

/** A reaction must be exactly one custom emoji, not text surrounding one. */
export const CUSTOM_EMOJI_TOKEN = /^<:[a-zA-Z0-9_]{2,32}:[a-z0-9]+>$/;

export function customEmojiToken(emoji: Pick<CustomEmoji, "id" | "name">) {
  return `<:${emoji.name}:${emoji.id}>`;
}

export function customEmojiIds(content: string): string[] {
  const ids: string[] = [];
  CUSTOM_EMOJI_PATTERN.lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = CUSTOM_EMOJI_PATTERN.exec(content)) !== null)
    ids.push(match[2]);
  return Array.from(new Set(ids));
}
