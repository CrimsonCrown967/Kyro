export function findAvatarDecoration(id: string | null | undefined) {
  if (!id) return null;
  return AVATAR_DECORATIONS.find((item) => item.id === id) ?? null;
}

export function findProfileDecoration(id: string | null | undefined) {
  if (!id) return null;
  return PROFILE_DECORATIONS.find((item) => item.id === id) ?? null;
}
